// Compiles the Tailwind classes used by the published-page renderer helpers
// (src/helpers/**, src/components/PuckEditor/htmlExport.ts) into a single
// minified CSS string, and writes it into src/generated/publishedPageStyles.ts
// as a plain exported constant.
//
// That generated module is imported and inlined into a <style> tag by every
// renderer that builds a full published-page HTML document, replacing the
// old Tailwind Play CDN <script> tag (which caused a flash of unstyled
// content on every page load, since it only applies styles after scanning
// the already-rendered DOM at runtime).
//
// Run via `npm run build:published-styles` (also wired into `npm run build`).

import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, unlinkSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const rootDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
// Resolve the CLI through Node so it works when npm workspaces hoist tailwindcss to the repo root.
const tailwindCli = createRequire(import.meta.url).resolve('tailwindcss/lib/cli.js');
const configPath = path.join(rootDir, 'tailwind.published.config.ts');
const entryCssPath = path.join(rootDir, 'src', 'styles', 'published-page.tailwind-entry.css');
const tmpOutPath = path.join(rootDir, 'src', 'generated', '.publishedPageStyles.tmp.css');
const outModulePath = path.join(rootDir, 'src', 'generated', 'publishedPageStyles.ts');

execFileSync(
  process.execPath,
  [tailwindCli, '-c', configPath, '-i', entryCssPath, '-o', tmpOutPath, '--minify'],
  { stdio: 'inherit' }
);

const compiledCss = readFileSync(tmpOutPath, 'utf8')
  .replace(/\\/g, '\\\\')
  .replace(/`/g, '\\`')
  .replace(/\$\{/g, '\\${');

const moduleSource = `// AUTO-GENERATED by scripts/build-published-styles.mjs — DO NOT EDIT.
// Regenerate with: npm run build:published-styles
export const PUBLISHED_PAGE_STYLES = \`${compiledCss}\`;
`;

writeFileSync(outModulePath, moduleSource);
unlinkSync(tmpOutPath);

console.log(`[build-published-styles] wrote ${outModulePath} (${(compiledCss.length / 1024).toFixed(1)} KB)`);
